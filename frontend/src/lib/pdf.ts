// Minimal PDF writer for generated documents and reports (no dependency).
// Text only: a bold title, then lines that wrap and flow onto new pages.

const W = 595; // A4 in points
const H = 842;
const M = 56;
const SIZE = 10.5;
const LEAD = 15;
const CHARS = 92; // wrap width for Helvetica at this size

// Characters outside Latin-1 that our documents use.
const MAP: Record<string, string> = { "→": "->", "≥": ">=", "≤": "<=", "₂": "2", "•": "\x95", "–": "\x96", "—": "\x97", "’": "\x92", "‘": "\x91", "“": "\x93", "”": "\x94", "…": "...", "€": "\x80" };

function enc(s: string) {
  let out = "";
  for (const ch of s) {
    const c = MAP[ch] ?? ch;
    for (const k of c) {
      const code = k.charCodeAt(0);
      if (k === "(" || k === ")" || k === "\\") out += "\\" + k;
      else if (code < 32) continue;
      else if (code > 126) out += code < 256 ? "\\" + code.toString(8).padStart(3, "0") : "?";
      else out += k;
    }
  }
  return out;
}

function wrap(line: string) {
  if (line.length <= CHARS) return [line];
  const indent = line.match(/^\s*/)![0];
  const out: string[] = [];
  let cur = "";
  for (const word of line.trim().split(/\s+/)) {
    if ((cur + " " + word).trim().length > CHARS - indent.length) {
      out.push(indent + cur);
      cur = word;
    } else cur = (cur + " " + word).trim();
  }
  if (cur) out.push(indent + cur);
  return out;
}

/** Builds a PDF from a title and body lines. */
export function buildPDF(title: string, lines: string[]): Blob {
  const body = lines.flatMap(wrap);
  const perPage = Math.floor((H - 2 * M - 60) / LEAD);
  const pages: string[][] = [];
  for (let i = 0; i < Math.max(1, body.length); i += perPage) pages.push(body.slice(i, i + perPage));
  const stamp = new Date().toLocaleDateString("en-GB", { day: "2-digit", month: "short", year: "numeric" });

  const objs: string[] = [];
  objs[1] = "<< /Type /Catalog /Pages 2 0 R >>";
  objs[3] = "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>";
  objs[4] = "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>";
  const kids: number[] = [];
  pages.forEach((pg, i) => {
    const pageId = 5 + i * 2;
    const contentId = pageId + 1;
    kids.push(pageId);
    let y = H - M;
    let s = `0.12 0.36 0.23 rg BT /F2 9 Tf ${M} ${y} Td (MINENET) Tj ET 0 0 0 rg\n`;
    y -= 26;
    if (i === 0) {
      s += `BT /F2 16 Tf ${M} ${y} Td (${enc(title)}) Tj ET\n`;
      y -= 28;
    }
    for (const l of pg) {
      const bold = /^[A-Z0-9 &·:\-()]{4,}:?$/.test(l.trim()) && l.trim() === l.trim().toUpperCase();
      s += `BT /F${bold ? 2 : 1} ${SIZE} Tf ${M} ${y} Td (${enc(l)}) Tj ET\n`;
      y -= LEAD;
    }
    s += `0.45 0.45 0.45 rg BT /F1 8 Tf ${M} ${M - 24} Td (${enc(`Generated by MineNet on ${stamp} · Page ${i + 1} of ${pages.length}`)}) Tj ET\n`;
    objs[pageId] = `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${W} ${H}] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents ${contentId} 0 R >>`;
    objs[contentId] = `<< /Length ${s.length} >>\nstream\n${s}endstream`;
  });
  objs[2] = `<< /Type /Pages /Kids [${kids.map((k) => `${k} 0 R`).join(" ")}] /Count ${kids.length} >>`;

  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [];
  for (let i = 1; i < objs.length; i++) {
    offsets[i] = pdf.length;
    pdf += `${i} 0 obj\n${objs[i]}\nendobj\n`;
  }
  const xref = pdf.length;
  pdf += `xref\n0 ${objs.length}\n0000000000 65535 f \n`;
  for (let i = 1; i < objs.length; i++) pdf += `${String(offsets[i]).padStart(10, "0")} 00000 n \n`;
  pdf += `trailer\n<< /Size ${objs.length} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;
  // Every char is single-byte (escaped above), so offsets match bytes.
  const bytes = new Uint8Array(pdf.length);
  for (let i = 0; i < pdf.length; i++) bytes[i] = pdf.charCodeAt(i) & 0xff;
  return new Blob([bytes], { type: "application/pdf" });
}
